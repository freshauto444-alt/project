type TranslationKey = keyof typeof translations.uk

export function t(key: TranslationKey, lang: Language, vars?: Record<string, string | number>): string {
  const base: string = (translations[lang] as Record<string, string>)?.[key]
    || (translations.uk as Record<string, string>)[key]
    || (key as string)
  if (!vars) return base
  return base.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`))
}

